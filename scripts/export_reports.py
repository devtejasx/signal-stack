"""Export the sample reports and test evidence from the database into reports/.

    python scripts/export_reports.py
Creates per company: brief.md, brief.html, interview.md, profile.md, signal_stack.md, audit.md,
(revision.md), and reports/MINIMUM_TARGETS.md with the assignment's minimum-output checklist
computed from the live database.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from signalstack import db  # noqa: E402
from signalstack.profile import FIELD_LABEL, get_profile  # noqa: E402

OUT = ROOT / "reports"


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def md_escape(s) -> str:
    return str(s or "").replace("|", "/").replace("\n", " ")


def export_company(c: dict) -> dict:
    cid = c["id"]
    d = OUT / slug(c["name"])
    d.mkdir(parents=True, exist_ok=True)
    p = get_profile(cid)
    stats = {}

    b = db.one("SELECT * FROM briefs WHERE company_id=? ORDER BY id DESC LIMIT 1", (cid,))
    if b:
        (d / "brief.md").write_text(b["markdown"], encoding="utf-8")
        (d / "brief.html").write_text(b["html"], encoding="utf-8")

    # interview transcript
    qs = db.q("SELECT * FROM interview_questions WHERE company_id=? ORDER BY seq, is_followup, id", (cid,))
    L = [f"# Founder interview — {c['name']}", "",
         "> Demo answers were written by the candidate from public information about the company (not by the company). "
         "Questions were generated by the system from the company's research.", ""]
    n = 0
    for q in qs:
        if not q["is_followup"]:
            n += 1
        tag = "Follow-up" if q["is_followup"] else f"Q{n}"
        L.append(f"**{tag} · {FIELD_LABEL.get(q['area'], q['area'])}** — {q['question']}")
        if q["rationale"]:
            L.append(f"*Why asked:* {q['rationale']} *(generated by {q['generated_by']})*")
        L.append("")
        L.append("> " + (q["answer"] if q["status"] == "answered" else "*(skipped — confidential)*"))
        L.append("")
    (d / "interview.md").write_text("\n".join(L), encoding="utf-8")
    stats["questions"] = sum(1 for q in qs if not q["is_followup"])
    stats["followups"] = sum(1 for q in qs if q["is_followup"])

    # profile + facts
    facts = db.q("SELECT * FROM facts WHERE company_id=? ORDER BY kind DESC, id", (cid,))
    L = [f"# Company intelligence profile — {c['name']}", "", f"**Website:** {c['website']}", "",
         f"**Summary:** {p.get('summary')}", "", f"**Industry:** {p.get('industry')} · **Business model:** {p.get('business_model')}", ""]
    for k in ("offerings", "customer_segments", "geographies", "category_keywords", "customer_problem_queries", "market_topics", "regulatory_topics"):
        L.append(f"- **{k.replace('_', ' ')}:** {', '.join(map(str, p.get(k, []) or []))}")
    L += ["", "## Verified facts (matched against fetched pages)"]
    L += [f"- {f['statement']} — [{f['verification']}]({f['source_url']})" for f in facts if f["kind"] == "fact"]
    L += ["", "## Assumptions (to be confirmed)"]
    L += [f"- {f['statement']} — *{f['verification']}*" for f in facts if f["kind"] == "assumption"]
    L += ["", "## Founder intelligence"]
    for k, v in (p.get("intelligence") or {}).items():
        L.append(f"- **{FIELD_LABEL.get(k, k)}:** " + " | ".join((x.get("text") if isinstance(x, dict) else str(x)) for x in v))
    (d / "profile.md").write_text("\n".join(L), encoding="utf-8")

    # signal stack
    comps = db.q("SELECT * FROM competitors WHERE company_id=? ORDER BY status, similarity DESC", (cid,))
    src = db.q("SELECT * FROM sources WHERE company_id=? ORDER BY category, status, overall_score DESC", (cid,))
    L = [f"# Signal Stack — {c['name']}", "", "## Competitor profiles", "",
         "| Competitor | Website | Status | Homepage similarity | Why / verification | Found via |", "|---|---|---|---|---|---|"]
    for k in comps:
        L.append(f"| {k['name']} | {k['website'] or ''} | {k['status']} | {k['similarity'] if k['similarity'] is not None else '—'} | "
                 f"{md_escape(k['why'])} | {k['discovered_via']} |")
    for cat in ("customers", "competitors", "market", "internal"):
        L += ["", f"## {cat.title()} sources", "", "| Source | Type | Status | Specific | Recent | Credible | Overall | Reason | URL |",
              "|---|---|---|---|---|---|---|---|---|"]
        for s in [s for s in src if s["category"] == cat]:
            fmt = lambda v: f"{v:.2f}" if v is not None else "—"  # noqa: E731
            L.append(f"| {md_escape(s['name'])} | {s['type']} | {s['status']} | {fmt(s['specific_score'])} | {fmt(s['recency_score'])} | "
                     f"{fmt(s['credibility_score'])} | {fmt(s['overall_score'])} | {md_escape(s['reason'])} | {s['url'] or ''} |")
    (d / "signal_stack.md").write_text("\n".join(L), encoding="utf-8")

    a = db.one("SELECT * FROM audits WHERE company_id=? ORDER BY id DESC LIMIT 1", (cid,))
    if a:
        (d / "audit.md").write_text(a["markdown"], encoding="utf-8")
    r = db.one("SELECT * FROM stack_revisions WHERE company_id=? ORDER BY id DESC LIMIT 1", (cid,))
    if r:
        (d / "context_change_revision.md").write_text(r["markdown"], encoding="utf-8")

    stats.update({
        "approved_sources": sum(1 for s in src if s["status"] == "approved"),
        "sources_by_cat": {cat: sum(1 for s in src if s["status"] == "approved" and s["category"] == cat)
                           for cat in ("customers", "competitors", "market", "internal")},
        "competitors_approved": sum(1 for k in comps if k["status"] == "approved"),
        "records": db.scalar("SELECT COUNT(*) FROM items WHERE company_id=?", (cid,)),
        "records_external": db.scalar("SELECT COUNT(*) FROM items WHERE company_id=? AND category!='internal'", (cid,)),
        "significant": db.scalar("SELECT COUNT(*) FROM items WHERE company_id=? AND significant=1", (cid,)),
        "with_links": db.scalar("SELECT COUNT(*) FROM items WHERE company_id=? AND url IS NOT NULL AND url!=''", (cid,)),
        "crawls": db.scalar("SELECT COUNT(*) FROM crawl_runs WHERE company_id=?", (cid,)),
        "briefs": db.scalar("SELECT COUNT(*) FROM briefs WHERE company_id=?", (cid,)),
        "audits": db.scalar("SELECT COUNT(*) FROM audits WHERE company_id=?", (cid,)),
        "revisions": db.scalar("SELECT COUNT(*) FROM stack_revisions WHERE company_id=?", (cid,)),
    })
    return stats


def main() -> None:
    db.init_db()
    OUT.mkdir(exist_ok=True)
    rows = []
    for c in db.q("SELECT * FROM companies ORDER BY id"):
        rows.append((c, export_company(c)))
    total_ext = sum(s["records_external"] for _, s in rows)
    mu = next((s for c, s in rows if "meetuniversity" in c["domain"]), None)
    L = ["# Minimum working output — checklist (computed from the live database)", "",
         "| Requirement | Result |", "|---|---|",
         f"| One fully configured company: MeetUniversity | {'yes' if mu else 'no'} |",
         f"| Two additional company configurations | {len(rows) - (1 if mu else 0)} |",
         f"| 10-question adaptive interview | " + "; ".join(f"{c['name']}: {s['questions']} core + {s['followups']} follow-ups" for c, s in rows) + " |",
         f"| Four functioning Signal Stack categories | " + "; ".join(f"{c['name']}: {s['sources_by_cat']}" for c, s in rows) + " |",
         f"| ≥ 20 approved sources for MeetUniversity | {mu['approved_sources'] if mu else 0} |",
         f"| 5–10 competitor profiles | " + "; ".join(f"{c['name']}: {s['competitors_approved']}" for c, s in rows) + " |",
         f"| ≥ 30 actual collected intelligence records | {total_ext} external records (+ internal upload records) |",
         f"| Evidence + links for every development | " + "; ".join(f"{c['name']}: {s['with_links']}/{s['records']}" for c, s in rows) + " |",
         f"| One Monday brief per company | " + "; ".join(f"{c['name']}: {s['briefs']}" for c, s in rows) + " |",
         "| Working weekly scheduling mechanism | APScheduler cron per company (see Runs & Failures / Settings) |",
         f"| Monthly source-health audit | " + "; ".join(f"{c['name']}: {s['audits']}" for c, s in rows) + " |",
         "| Source addition/removal | Source Manager (add / approve / reject / remove / restore) |",
         f"| Historical crawl and brief records | " + "; ".join(f"{c['name']}: {s['crawls']} crawls, {s['briefs']} briefs" for c, s in rows) + " |",
         f"| Business-context change for one company | " + "; ".join(f"{c['name']}: {s['revisions']}" for c, s in rows if s["revisions"]) + " |",
         ]
    (OUT / "MINIMUM_TARGETS.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
